import { existsSync } from 'node:fs';
import { lstat, mkdir, readFile, realpath, writeFile } from 'node:fs/promises';
import path from 'node:path';

// Antigravity chooses its own model after Google account sign-in. This module
// only configures Code Bridge's MCP tools for the selected local workspace.
export function createAntigravityProxy({ getStatus, origin }) {
  const endpoint = `${origin}/mcp`;
  const entry = { serverUrl: endpoint };
  const snippet = JSON.stringify({ mcpServers: { 'code-bridge': entry } }, null, 2);

  function configPath() {
    return path.join(getStatus().workspace, '.agents', 'mcp_config.json');
  }

  async function configured() {
    try {
      const data = JSON.parse(await readFile(configPath(), 'utf8'));
      return data?.mcpServers?.['code-bridge']?.serverUrl === endpoint;
    } catch { return false; }
  }

  async function status() {
    return {
      workspace: getStatus().workspace,
      mcpEndpoint: endpoint,
      configPath: '.agents/mcp_config.json',
      isConfigured: await configured(),
      mcpConfigSnippet: snippet,
      globalMcpSnippet: snippet
    };
  }

  async function configureWorkspace() {
    const workspace = await realpath(getStatus().workspace);
    const directory = path.join(workspace, '.agents');
    await mkdir(directory, { recursive: true });
    if (await realpath(directory) !== directory) throw new Error('Thư mục .agents không được là liên kết ra ngoài workspace.');
    const file = path.join(directory, 'mcp_config.json');
    let data = {};
    if (existsSync(file)) {
      if ((await lstat(file)).isSymbolicLink()) throw new Error('mcp_config.json không được là liên kết tượng trưng.');
      data = JSON.parse(await readFile(file, 'utf8'));
      if (!data || typeof data !== 'object' || Array.isArray(data)) throw new Error('Cấu hình MCP hiện tại không hợp lệ.');
    }
    const servers = { ...(data.mcpServers || {}) };
    // Remove only entries generated by the earlier experimental bridge.
    if (servers['gemini-argon-bridge']?.serverUrl?.endsWith('/api/antigravity/sse')) delete servers['gemini-argon-bridge'];
    if (Array.isArray(servers['code-bridge-filesystem']?.args) &&
        servers['code-bridge-filesystem'].args[0]?.replace(/\\/g, '/').endsWith('/upstream/mcp-servers/src/filesystem/dist/index.js'))
      delete servers['code-bridge-filesystem'];
    data.mcpServers = { ...servers, 'code-bridge': entry };
    await writeFile(file, JSON.stringify(data, null, 2) + '\n', { mode: 0o600 });
    return { ok: true, path: file, configured: true };
  }

  return { status, configureWorkspace };
}
